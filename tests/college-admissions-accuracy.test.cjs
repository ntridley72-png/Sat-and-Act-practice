const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const profile = {college:{testType:'sat',sat:1200,gpa:3.7,gpaScale:'4uw'},history:[]};
const context = vm.createContext({console,profile,state:{view:'start',plan:{},keys:[],answers:{},done:false},cloud:{user:null},document:{addEventListener(){},querySelectorAll(){return[];},querySelector(){return null;}},$(){return null;},render(){},showScreen(){},saveProfile(){},predictScores(){return{sat:{},act:{}};},escapeHtml:String,localStorage:{getItem(){return null;},setItem(){}},setTimeout,clearTimeout});
context.window = context;
if (fs.existsSync('admissions-model.js')) vm.runInContext(fs.readFileSync('admissions-model.js','utf8'),context);
vm.runInContext(fs.readFileSync('college-data.js','utf8'),context);
vm.runInContext(fs.readFileSync('college.js','utf8'),context);
const college = {id:110662,n:'Test-blind university',st:'CA',ctrl:'public',adm:9,sr25:1200,sr75:1400};
const low = context.collegeFeature.estimateCollege(college);
profile.college.sat = 1600;
const high = context.collegeFeature.estimateCollege(college);
assert.equal(high.estimate,low.estimate,'test-blind admission estimates must ignore SAT even when a historical range exists');
assert.equal(high.confidence,'uncalibrated','profile completeness is not statistical validation');
assert.equal(high.calibrated,false,'no applicant outcome data means no calibrated probability');
assert.equal(high.probability,null,'an unvalidated percentage must not be exposed as a probability');
const model = require('../admissions-model.js');
const observed = model.reportedRate({adm:9,admissions:{applicants:145085,admitted:13659,year:2025,sourceUrl:'https://admission.ucla.edu/apply/first-year/first-year-profile/2025',verifiedAt:'2026-10-14',population:'First-time, first-year applicants; all rounds'}});
assert.ok(Math.abs(observed.rate-13659/145085*100)<1e-10,'rate uses the published denominator, not rounded display text');
assert.equal(observed.year,2025);
assert.equal(observed.countsKnown,true);
assert.equal(model.reportedRate({adm:0}).rate,0,'zero is not missing');
assert.equal(model.reportedRate({adm:100}).rate,100,'100% is not capped at 95%');
assert.equal(model.reportedRate({adm:null}).rate,null,'missing is never replaced by a made-up prior');
assert.equal(model.reportedRate({adm:120}).rate,null,'invalid source values are quarantined');
assert.equal(model.reportedRate({adm:9,admissions:{applicants:10,admitted:11}}).countsKnown,false,'invalid counts cannot override official rates');
assert.equal(model.reportedRate({adm:9,admissions:{applicants:10,admitted:5,year:2025,sourceUrl:'javascript:alert(1)'}}).countsKnown,false,'unsafe URLs cannot supply evidence');
const other = {...college,st:'TX',ctrl:'private',test:'Not considered'};
profile.college.sat=1200;const a=context.collegeFeature.estimateCollege(other);
profile.college.sat=1600;assert.equal(context.collegeFeature.estimateCollege(other).estimate,a.estimate,'explicit test-not-considered policy is respected outside California');
console.log('PASS: test-blind policy, uncalibrated-probability gate, precise reported rates, missing/zero/invalid data and safe provenance.');
